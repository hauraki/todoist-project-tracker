import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { copyFileSync, watch } from 'node:fs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'dist/main.js',
	minify: prod,
});

/** styles.css is not part of the JS graph, so copy it next to main.js ourselves. */
const copyStyles = () => copyFileSync('styles.css', 'dist/styles.css');

if (prod) {
	await context.rebuild();
	copyStyles();
	process.exit(0);
} else {
	copyStyles();
	watch('styles.css', () => {
		try {
			copyStyles();
			console.log('[watch] copied styles.css');
		} catch (e) {
			console.error('[watch] failed to copy styles.css', e);
		}
	});
	await context.watch();
}
