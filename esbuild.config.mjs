import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { copyFileSync, watch } from 'node:fs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'dist/main.js',
	minify: prod,
});

/** These files are not part of the JS graph, so copy them next to main.js ourselves. */
const STATIC_FILES = ['styles.css', 'manifest.json'];
const copyStatic = (file) => copyFileSync(file, `dist/${file}`);

if (prod) {
	await context.rebuild();
	STATIC_FILES.forEach(copyStatic);
	process.exit(0);
} else {
	for (const file of STATIC_FILES) {
		copyStatic(file);
		watch(file, () => {
			try {
				copyStatic(file);
				console.log(`[watch] copied ${file}`);
			} catch (e) {
				console.error(`[watch] failed to copy ${file}`, e);
			}
		});
	}
	await context.watch();
}
